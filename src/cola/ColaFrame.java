    public static void main(String args[]) throws InterruptedException, IOException {

        // ********************************* Iniciamos frame y canvas *********************************
        final int ancho = 1200, alto = 600;

        ColaFrame elframe = new ColaFrame();
        CanvasCola vista = new CanvasCola(ancho, alto);

        elframe.setSize(ancho, alto);
        //elframe.setBackground(Color.red);
        elframe.add(vista);

        elframe.setVisible(true);

        // ************************************** Iniciar hilos  **************************************
        ColaLenta cola = new ColaLenta(TAMANO_COLA, vista);

        Productor[] productores = new Productor[NUMERO_PRODUCTORES];
        Thread[] consumidores = new Thread[NUMERO_CONSUMIDORES];
        // creacion hilos
        for (int i = 0; i < NUMERO_PRODUCTORES; i++) {
            productores[i] = new Productor("P" + (i + 1), cola);
        }

        for (int i = 0; i < NUMERO_CONSUMIDORES; i++) {
            consumidores[i] = new Thread(
                    new Consumidor("C" + (i + 1), cola));
        }

        // lanzamiento hilos
        for (int i = 0; i < NUMERO_PRODUCTORES; i++) {
            productores[i].start();
        }

        for (int i = 0; i < NUMERO_CONSUMIDORES; i++) {
            consumidores[i].start();
        }

        // esperar hilos
        for (int i = 0; i < NUMERO_PRODUCTORES; i++) {
            productores[i].join();
        }

        for (int i = 0; i < NUMERO_CONSUMIDORES; i++) {
            consumidores[i].join();
        }

        Thread.sleep(3000);
        System.exit(0);
    }


